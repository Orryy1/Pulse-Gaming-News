/** Upper case, accents dropped, typographic quotes and dashes made plain. */
export function pixelNormal(t: string): string {
  return t
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[\u2018\u2019\u02bc]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2013\u2014\u2212]/g, "-")
    .replace(/\u2026/g, "...")
    .toUpperCase();
}

/** True when every character of the text has a glyph. */
export function pixelReady(t: string): boolean {
  return [...pixelNormal(t)].every((c) => c in G);
}

const cache = new Map<string, string>();
const DOT = 0.84;
const PAD = (1 - DOT) / 2;

/** One glyph's path at column offset x (in pixel units: a glyph is 5 wide, advances 6, is 7 tall). */
function glyph(c: string, x: number): string {
  const rows = (G[c] ?? G[" "]!).split("|");
  let d = "";
  rows.forEach((row, y) => {
    for (let i = 0; i < row.length; i++)
      if (row[i] === "#") d += `M${x + i + PAD} ${y + PAD}h${DOT}v${DOT}h-${DOT}z`;
  });
  return d;
}

/** The path of a line of text and its width in pixel units (6 per character, less the last gap). */
export function pixelPath(t: string): { d: string; w: number } {
  const s = pixelNormal(t);
  const hit = cache.get(s);
  const w = Math.max(0, s.length * 6 - 1);
  if (hit !== undefined) return { d: hit, w };
  let d = "";
  [...s].forEach((c, i) => {
    d += glyph(c, i * 6);
  });
  if (cache.size > 400) cache.clear();
  cache.set(s, d);
  return { d, w };
}
